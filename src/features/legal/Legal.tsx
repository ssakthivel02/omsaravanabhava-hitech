import { completeness } from '@/content';

interface Section {
  h: string;
  body: string[];
}

function Doc({ title, intro, sections }: { title: string; intro: string; sections: Section[] }) {
  return (
    <article className="page">
      <header className="page-head">
        <h1 lang="ta">{title}</h1>
        <p lang="ta">{intro}</p>
      </header>
      {sections.map((s) => (
        <section key={s.h}>
          <h2 lang="ta">{s.h}</h2>
          <ul className="prose-list" lang="ta">
            {s.body.map((b) => (
              <li key={b}>{b}</li>
            ))}
          </ul>
        </section>
      ))}
    </article>
  );
}

